<script setup>
import { nextTick, onBeforeUnmount, onMounted, ref, watch } from 'vue';
import { getData, postData } from '../../plugins/axios.js';
import { getCurrentLocale } from '../../plugins/i18n.js';

let carouselFrame = null;
const recentProjects = ref([]);
const homeProjectsLoading = ref(true);
const homeProjectsError = ref('');
const recentBlogs = ref([]);
const homeBlogsLoading = ref(true);
const homeBlogsError = ref('');
const publishedTestimonials = ref([]);
const homeTestimonialsLoading = ref(true);
const homeTestimonialsError = ref('');
const newsletterEmail = ref('');
const newsletterLoading = ref(false);
const newsletterMessage = ref('');
const newsletterError = ref('');

const subscribeToNewsletter = async () => {
  newsletterLoading.value = true;
  newsletterMessage.value = '';
  newsletterError.value = '';

  try {
    const response = await postData('/newsletter/subscribe', {
      email: newsletterEmail.value,
      language: getCurrentLocale() === 'en' ? 'en' : 'fr',
    });
    newsletterMessage.value = response.message;
    newsletterEmail.value = '';
  } catch (error) {
    newsletterError.value = error.response?.data?.message || 'Unable to subscribe right now.';
  } finally {
    newsletterLoading.value = false;
  }
};

const projectImageUrl = (path) => path?.startsWith('http') ? path : `/storage/${path}`;
const blogImageUrl = (path) => path?.startsWith('http') ? path : `/storage/${path}`;
const formatBlogDate = (date) => date
  ? new Intl.DateTimeFormat('en-US', { month: 'long', day: 'numeric', year: 'numeric' }).format(new Date(date))
  : 'Recent article';

const initCarousels = () => {
  const $ = window.jQuery;
  if (!$?.fn?.owlCarousel) return;

  const carousels = [
    {
      selector: '.slider_list',
      options: {
        loop: true,
        autoplay: true,
        autoplayTimeout: 3000,
        autoplayHoverPause: false,
        smartSpeed: 700,
        dots: false,
        nav: true,
                navText: ["<i class='fa fa-long-arrow-left'></i>", "<i class='fa fa-long-arrow-right'></i>"],
        items: 1,
      },
    },
    {
      selector: '.case_study_list',
      options: {
        loop: true,
        autoplay: true,
        autoplayTimeout: 4000,
        smartSpeed: 2000,
        dots: true,
        nav: false,
        responsive: { 0: { items: 1 }, 768: { items: 3 }, 992: { items: 4 }, 1920: { items: 5 } },
      },
    },
    {
      selector: '.testimonial_list',
      options: {
        loop: true,
        autoplay: true,
        autoplayTimeout: 10000,
        smartSpeed: 700,
        dots: true,
        nav: false,
        responsive: { 0: { items: 1 }, 768: { items: 2 }, 992: { items: 3 } },
      },
    },
  ];

  carousels.forEach(({ selector, options }) => {
    const carousel = $(selector);
    if (!carousel.length) return;
    if (carousel.hasClass('owl-loaded')) carousel.trigger('destroy.owl.carousel');
    carousel.owlCarousel(options);
  });
};

const scheduleCarouselInit = () => {
  nextTick(() => {
    carouselFrame = requestAnimationFrame(initCarousels);
  });
};

const loadRecentProjects = async () => {
  try {
    const response = await getData('/public/projects/recent');
    recentProjects.value = response.data ?? [];
    scheduleCarouselInit();
  } catch (error) {
    homeProjectsError.value = 'We could not load the latest projects right now.';
  } finally {
    homeProjectsLoading.value = false;
  }
};

const loadRecentBlogs = async () => {
  try {
    const response = await getData('/public/blogs/recent');
    recentBlogs.value = response.data ?? [];
    scheduleCarouselInit();
  } catch (error) {
    homeBlogsError.value = 'We could not load the latest articles right now.';
  } finally {
    homeBlogsLoading.value = false;
  }
};

const loadPublishedTestimonials = async () => {
  try {
    const response = await getData('/public/testimonials');
    publishedTestimonials.value = Array.isArray(response) ? response : response.data ?? [];
    scheduleCarouselInit();
  } catch (error) {
    homeTestimonialsError.value = 'We could not load the testimonials right now.';
  } finally {
    homeTestimonialsLoading.value = false;
  }
};

onMounted(() => {
  window.addEventListener('user-template-ready', scheduleCarouselInit);
  scheduleCarouselInit();
    loadRecentProjects();
  loadRecentBlogs();
    loadPublishedTestimonials();
});

watch(recentProjects, scheduleCarouselInit);
watch(recentBlogs, scheduleCarouselInit);
  watch(publishedTestimonials, scheduleCarouselInit);

onBeforeUnmount(() => {
  window.removeEventListener('user-template-ready', scheduleCarouselInit);
  if (carouselFrame) cancelAnimationFrame(carouselFrame);
});
</script>

